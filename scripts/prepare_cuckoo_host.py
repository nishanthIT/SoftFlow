"""Privileged host setup for the dedicated, non-routed Cuckoo guest bridge.

Usage: sudo python3 scripts/prepare_cuckoo_host.py
Uses the public plan generated by `cuckoo_guest.py host-plan`.
Does not replace existing firewall tables, routes or QEMU ACL rules.
"""
import grp
import argparse
import ipaddress
import json
import os
from pathlib import Path
import pwd
import re
import shutil
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[1]


def command(*args,**kwargs):
    return subprocess.run(list(args),check=True,**kwargs)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--plan',type=Path,default=ROOT/'.local/run/cuckoo-host-plan.json')
    parser.add_argument('--user',default=os.environ.get('SUDO_USER'))
    parser.add_argument('--install-service',action='store_true',help='Install a root-owned boot service to restore the isolated bridge after reboot')
    args=parser.parse_args()
    if os.geteuid()!=0:raise RuntimeError('Run this host setup script with sudo')
    plan=json.loads(args.plan.read_text())
    username=args.user
    if not username or username=='root':raise RuntimeError('Run sudo from the normal application user')
    account=pwd.getpwnam(username)
    if account.pw_uid!=plan['uid']:raise RuntimeError('Host plan belongs to another user')
    bridge=plan['interface']
    if not re.fullmatch(r'ss-[a-zA-Z0-9_-]{1,11}',bridge):raise RuntimeError('Use a dedicated interface name beginning ss- (maximum 14 characters)')
    network=ipaddress.ip_network(plan['network']);address=ipaddress.ip_address(plan['resultserver_ip'])
    if network.version!=4 or not network.is_private or address not in network:raise RuntimeError('Use a private IPv4 guest subnet')
    port=int(plan['resultserver_port'])
    if not 1024<=port<=65535:raise RuntimeError('Invalid resultserver port')
    for binary in ['ip','nft','setcap','setfacl','tcpdump']:
        if not shutil.which(binary):raise RuntimeError('Required host command missing: '+binary)
    devices=json.loads(command('ip','-j','address','show',capture_output=True,text=True).stdout)
    for device in devices:
        if device['ifname']==bridge:continue
        for info in device.get('addr_info',[]):
            if info['family']=='inet' and network.overlaps(ipaddress.ip_network(info['local']+'/'+str(info['prefixlen']),strict=False)):
                raise RuntimeError('Guest subnet overlaps existing interface '+device['ifname'])
    existing=next((d for d in devices if d['ifname']==bridge),None)
    if existing:
        if not Path('/sys/class/net',bridge,'bridge').exists():raise RuntimeError('Requested interface already exists and is not a bridge')
        addresses=[a['local'] for a in existing.get('addr_info',[]) if a['family']=='inet']
        if addresses and addresses!=[str(address)]:raise RuntimeError('Existing bridge has different addresses')
    else:command('ip','link','add',bridge,'type','bridge')
    # Dedicated table; transactional replacement leaves other firewalls intact.
    rules=f'''table inet sentinelscan_cuckoo {{
 chain input {{ type filter hook input priority -200; policy accept;
  iifname "{bridge}" ct state established,related accept
  iifname "{bridge}" ip daddr {address} tcp dport {port} accept
  iifname "{bridge}" drop
 }}
 chain forward {{ type filter hook forward priority -200; policy accept;
  iifname "{bridge}" drop
  oifname "{bridge}" drop
 }}
}}
'''
    existing_table=subprocess.run(['nft','list','table','inet','sentinelscan_cuckoo'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL).returncode==0
    command('nft','-f','-',input=('delete table inet sentinelscan_cuckoo\n' if existing_table else '')+rules,text=True)
    command('ip','address','replace',str(address)+'/'+str(network.prefixlen),'dev',bridge)
    command('ip','link','set',bridge,'up')
    acl=Path('/etc/qemu/bridge.conf');acl.parent.mkdir(exist_ok=True)
    text=acl.read_text() if acl.exists() else ''
    line='allow '+bridge
    if line not in text.splitlines():acl.write_text(text.rstrip()+'\n'+line+'\n')
    helper=next((p for p in [Path('/usr/lib/qemu/qemu-bridge-helper'),Path('/usr/libexec/qemu-bridge-helper')] if p.is_file()),None)
    if not helper:raise RuntimeError('QEMU bridge helper is not installed')
    private=Path('/usr/local/libexec/sentinelscan');private.mkdir(parents=True,exist_ok=True)
    private.chmod(0o750);os.chown(private,0,account.pw_gid)
    for source,name,mode in [(helper,'qemu-bridge-helper',0o4750),(Path(shutil.which('tcpdump')),'tcpdump',0o750)]:
        target=private/name;shutil.copyfile(source,target);os.chown(target,0,account.pw_gid);target.chmod(mode)
    command('setcap','cap_net_raw,cap_net_admin=eip',str(private/'tcpdump'))
    command('setfacl','-m',f'u:{account.pw_uid}:rw','/dev/kvm')
    if args.install_service:
        if not re.fullmatch(r'[a-z_][a-z0-9_-]*',username):raise RuntimeError('Unsupported service username')
        config=Path('/etc/sentinelscan');config.mkdir(exist_ok=True,mode=0o755)
        stored=config/'cuckoo-host.json';stored.write_text(json.dumps(plan,indent=2));stored.chmod(0o644);os.chown(stored,0,0)
        script=private/'host_setup.py';shutil.copyfile(__file__,script);script.chmod(0o700);os.chown(script,0,0)
        service=Path('/etc/systemd/system/sentinelscan-cuckoo-host.service')
        service.write_text(f'''[Unit]
Description=SentinelScan isolated Cuckoo guest bridge
After=network.target nftables.service

[Service]
Type=oneshot
ExecStart=/usr/bin/python3 {script} --plan={stored} --user={username}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
''')
        service.chmod(0o644);os.chown(service,0,0)
        command('systemctl','daemon-reload')
        command('systemctl','enable','sentinelscan-cuckoo-host.service')
        print('Root-owned host setup installed for subsequent boots.')
    print('Dedicated guest bridge configured with forwarding blocked and host access restricted to resultserver/replies.')
    print('Private QEMU helper and tcpdump are executable by the application user group only.')
    if not args.install_service:print('Re-run after reboot, or use --install-service once to restore host networking at boot.')


if __name__=='__main__':
    try:main()
    except (RuntimeError,OSError,subprocess.CalledProcessError) as error:
        print('Host setup failed: '+str(error),file=sys.stderr);sys.exit(1)
